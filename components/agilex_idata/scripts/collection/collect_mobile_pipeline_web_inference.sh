while [ "$#" -gt 0 ]; do
    case "$1" in
        -h|--help)
            usage
            exit 0
            ;;
        -d|--data-dir)
            [ "$#" -ge 2 ] || {
                echo "[错误] $1 需要数据集目录参数" >&2
                exit 1
            }
            DATA_DIR_ARG="$2"
            shift 2
            ;;
        --left-target|--target-a|--bottle-a)
            [ "$#" -ge 2 ] || {
                echo "[错误] $1 需要左臂物品参数" >&2
                exit 1
            }
