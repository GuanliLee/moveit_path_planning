        --left-target=*|--target-a=*|--bottle-a=*)
            LEFT_TARGET_ARG="${1#*=}"
            shift
            ;;
        --right-target=*|--target-b=*|--bottle-b=*)
            RIGHT_TARGET_ARG="${1#*=}"
            shift
            ;;
        --start-index=*)
            START_INDEX="${1#*=}"
