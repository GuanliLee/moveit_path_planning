class CollectionHttp:
    def __init__(self, base_url: str):
        parsed = urlparse(base_url)
        if parsed.scheme != "http" or not parsed.hostname or not parsed.port:
            raise ValueError(f"unsupported collection URL: {base_url}")
        self.host = parsed.hostname
        self.port = parsed.port

    def request(
        self,
        method: str,
        path: str,
        timeout: float = 10.0,
        *,
        body: bytes | None = None,
        headers: dict[str, str] | None = None,
    ) -> tuple[int, bytes]:
        conn = http.client.HTTPConnection(self.host, self.port, timeout=timeout)
        try:
            request_headers = {"Connection": "close"}
            if headers:
                request_headers.update(headers)
            if body is not None:
                request_headers["Content-Length"] = str(len(body))
            conn.request(method, path, body=body, headers=request_headers)
            resp = conn.getresponse()
            body = resp.read()
            if resp.status >= 400:
                raise RuntimeError(f"{method} {path} returned {resp.status}: {body[:300]!r}")
            return resp.status, body
        finally:
            conn.close()

    def status(self) -> dict:
        _, body = self.request("GET", "/status", timeout=5.0)
        return json.loads(body.decode("utf-8") or "{}")

    def post(self, path: str) -> None:
        self.request("POST", path, timeout=10.0)

    def post_json(self, path: str, payload: dict) -> None:
        body = json.dumps(payload, ensure_ascii=False).encode("utf-8")
        self.request(
            "POST",
            path,
            timeout=10.0,
            body=body,
            headers={"Content-Type": "application/json; charset=utf-8"},
        )


class StateMachineBridge(Node):
    def __init__(self):
        super().__init__("data_collection_state_machine_bridge")
        self.events: queue.SimpleQueue[str] = queue.SimpleQueue()
        self.inference_record_active = False
        self.state_machine_start_active = False
        ready_qos = QoSProfile(depth=1)
        ready_qos.reliability = ReliabilityPolicy.RELIABLE
        ready_qos.durability = DurabilityPolicy.TRANSIENT_LOCAL
        self.ready_pub = self.create_publisher(Bool, ready_topic, ready_qos)
        self.create_subscription(Bool, inference_record_topic, self._on_inference_record, 10)
        self.create_subscription(Bool, start_topic, self._on_start, 10)
        self.create_subscription(Bool, end_topic, self._on_end, 10)
        for stage_no, topics in stage_topic_groups:
            for topic in topics:
                self.create_subscription(
                    Bool,
                    topic,
                    lambda msg, stage_no=stage_no, topic=topic: self._on_stage(msg, stage_no, topic),
                    10,
                )

    def _on_inference_record(self, msg: Bool) -> None:
        self.inference_record_active = bool(msg.data)
        self.events.put("inference_record")

    def _on_start(self, msg: Bool) -> None:
        self.state_machine_start_active = bool(msg.data)
        self.events.put("start")

    def _on_end(self, msg: Bool) -> None:
        if msg.data:
            self.events.put("end")

    def _on_stage(self, msg: Bool, stage_no: int, topic: str) -> None:
        if msg.data:
            self.events.put(f"stage:{stage_no}:{topic}")

    def publish_ready(self, value: bool, repeats: int | None = None) -> None:
        msg = Bool()
        msg.data = bool(value)
        count = publish_repeats if repeats is None else max(1, int(repeats))
        for _ in range(count):
            self.ready_pub.publish(msg)
            try:
                rclpy.spin_once(self, timeout_sec=0.0)
            except ExternalShutdownException:
                return
            time.sleep(0.05)


def wait_for_status(http: CollectionHttp, predicate, timeout: float, label: str) -> dict:
    deadline = time.monotonic() + timeout
    last_status: dict = {}
    while rclpy.ok() and time.monotonic() < deadline:
        last_status = http.status()
        if predicate(last_status):
            return last_status
        time.sleep(max(0.05, poll_interval))
    raise TimeoutError(f"timed out waiting for {label}; last status={last_status}")


