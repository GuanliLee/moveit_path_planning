                last_event=last_event,
                inference_record_active=inference_record_active,
                state_machine_start_active=state_machine_start_active,
                active_stage=current_stage,
                completed_stages=as_int(status.get("completed_stages"), 0),
                episode_staged=episode_staged,
            )
            node.publish_ready(True)
            phase = "recording"
            return
        set_status(
            "starting",
            f"{reason}，正在按{mode_text}模式启动 episode{episode} 录制；尚未发布 {ready_topic}=true。",
            last_event=last_event,
            inference_record_active=inference_record_active,
            state_machine_start_active=state_machine_start_active,
            active_stage=current_stage,
            completed_stages=0,
            episode_staged=episode_staged,
        )
        if not status.get("capture_running"):
            http.post("/start")
        status = wait_for_status(
            http,
            is_recording_status,
            start_timeout,
            "collection to enter recording state",
        )
        log("collection recording; " + status_summary(status))
        episode = status.get("episode")
        current_stage = as_int(status.get("current_stage"), current_stage) if episode_staged else 0
        set_status(
            "recording",
            recording_wait_message(episode),
            last_event=last_event,
            inference_record_active=inference_record_active,
            state_machine_start_active=state_machine_start_active,
            active_stage=current_stage,
            completed_stages=as_int(status.get("completed_stages"), 0),
            episode_staged=episode_staged,
        )
        node.publish_ready(True)
        phase = "recording"

    def mark_stage_boundary(stage_no: int, topic: str) -> dict:
        nonlocal current_stage
        status = http.status()
        if not is_recording_status(status):
            raise RuntimeError(f"stage {stage_no} received while collection is not recording; {status_summary(status)}")
        episode = status.get("episode")
        set_status(
            "recording",
            f"收到 {topic}=true，正在结束阶段 {stage_no} 并进入阶段 {stage_no + 1}。",
            last_event=f"stage{stage_no}",
            active_stage=stage_no,
            completed_stages=as_int(status.get("completed_stages"), 0),
            episode_staged=True,
        )
        http.post("/stage")
        status = wait_for_status(
            http,
            lambda item: is_recording_status(item) and as_int(item.get("completed_stages"), 0) >= stage_no,
            start_timeout,
            f"collection to mark stage {stage_no}",
        )
        current_stage = as_int(status.get("current_stage"), stage_no + 1)
        log(f"stage {stage_no} marked by {topic}; current " + status_summary(status))
        set_status(
            "recording",
            recording_wait_message(episode),
            last_event=f"stage{stage_no}",
            active_stage=current_stage,
            completed_stages=as_int(status.get("completed_stages"), stage_no),
            episode_staged=True,
        )
        node.publish_ready(True, repeats=2)
        return status

    def save_current_episode(last_event: str = "end") -> dict:
        nonlocal phase, episode_staged, current_stage
        phase = "saving"
        set_status(
            "saving",
            f"收到 {end_topic}=true，正在停止并保存本条数据；已发布 {ready_topic}=false。",
            last_event=last_event,
            inference_record_active=inference_record_active,
            state_machine_start_active=state_machine_start_active,
            active_stage=current_stage,
            episode_staged=episode_staged,
        )
        node.publish_ready(False, repeats=2)
        status = http.status()
        log("end received; current " + status_summary(status))
        episode = status.get("episode")
        set_status(
            "saving",
            f"正在停止并保存 episode{episode}。",
            last_event=last_event,
            inference_record_active=inference_record_active,
            state_machine_start_active=state_machine_start_active,
            active_stage=current_stage,
            completed_stages=as_int(status.get("completed_stages"), 0),
            episode_staged=episode_staged,
        )
        if not status.get("capture_running"):
            log("save requested but collection was not running; " + status_summary(status))
            return status
        http.post("/save")
        status = wait_for_status(
            http,
            lambda item: (not bool(item.get("capture_running"))) and episode_changed(item, episode),
            save_timeout,
            "collection to finish saving and advance episode",
        )
        log("collection saved; " + status_summary(status))
        episode_staged = False
        current_stage = 0
        return status

    try:
        log(
            "bridge ready: "
            f"inference_record_topic={inference_record_topic}, start_topic={start_topic}, "
            f"end_topic={end_topic}, ready_topic={ready_topic}, "
            f"stage_topics={stage_topics_for_status}, collection={collection_url}, "
            f"enabled={enabled}, staged_enabled={staged_enabled}"
        )
        set_status(
            "idle" if enabled else "disabled",
            (
                enabled_idle_message()
                if enabled
                else "自动监听未启用；手动采集按钮可正常使用。"
            ),
            staged_enabled=staged_enabled,
            inference_record_active=inference_record_active,
            state_machine_start_active=state_machine_start_active,
            active_stage=0,
            completed_stages=0,
            episode_staged=False,
        )
        node.publish_ready(False, repeats=2)
        while rclpy.ok():
            try:
                rclpy.spin_once(node, timeout_sec=0.1)
            except ExternalShutdownException:
                break
            current_enabled = automation_enabled()
            current_staged_enabled = automation_staged_enabled()
            if current_enabled != enabled:
                enabled = current_enabled
                log(f"automatic collection {'enabled' if enabled else 'disabled'}")
                if not enabled:
                    phase = "idle"
                    set_status(
                        "disabled",
                        "自动监听已关闭；手动采集按钮可正常使用。",
                        inference_record_active=inference_record_active,
                        state_machine_start_active=state_machine_start_active,
                        active_stage=0,
                        completed_stages=0,
                        episode_staged=False,
                    )
                    node.publish_ready(False)
                else:
                    set_status(
                        "idle",
                        enabled_idle_message(),
                        inference_record_active=inference_record_active,
                        state_machine_start_active=state_machine_start_active,
                        active_stage=0,
                        completed_stages=0,
                        episode_staged=False,
                    )
            if current_staged_enabled != staged_enabled:
                staged_enabled = current_staged_enabled
                log(f"staged automatic collection {'enabled' if staged_enabled else 'disabled'}")
                if phase == "idle":
                    set_status(
                        "idle" if enabled else "disabled",
                        enabled_idle_message() if enabled else "自动监听未启用；手动采集按钮可正常使用。",
                        staged_enabled=staged_enabled,
                        inference_record_active=inference_record_active,
                        state_machine_start_active=state_machine_start_active,
                        active_stage=0,
                        completed_stages=0,
                        episode_staged=False,
                    )

            try:
                event = node.events.get_nowait()
            except queue.Empty:
                continue

            if event in {"inference_record", "start"}:
                inference_record_active = node.inference_record_active
                state_machine_start_active = node.state_machine_start_active

            if not enabled:
                log(f"ignore {event} while automatic collection is disabled")
                set_status(
                    "disabled",
                    f"自动监听未启用，已忽略状态机事件 {event}。",
                    last_event=event,
                    inference_record_active=inference_record_active,
                    state_machine_start_active=state_machine_start_active,
                )
                node.publish_ready(False, repeats=1)
                continue

            if event in {"inference_record", "start"}:
                if phase in {"starting", "saving"}:
                    log(f"ignore {event} while phase={phase}")
                    continue
                if phase == "recording":
                    status = http.status()
                    if is_recording_status(status):
                        log(f"{event} received while already recording; confirmed by status, republish ready=true")
                        set_status(
                            "recording",
                            recording_wait_message(status.get("episode")),
                            last_event=event,
                            inference_record_active=inference_record_active,
                            state_machine_start_active=state_machine_start_active,
                            active_stage=current_stage,
                            completed_stages=as_int(status.get("completed_stages"), 0),
                            episode_staged=episode_staged,
                        )
                        node.publish_ready(True)
                        continue
                    log("local recording phase was stale; collection status is " + status_summary(status))
                    phase = "idle"

                if not start_gate_open():
                    log(
                        "start gate waiting: "
                        f"inference_record={inference_record_active}, start={state_machine_start_active}"
                    )
                    if phase == "idle":
                        set_status(
                            "idle",
                            gate_wait_message(),
                            last_event=event,
                            inference_record_active=inference_record_active,
                            state_machine_start_active=state_machine_start_active,
                            active_stage=0,
                            completed_stages=0,
                            episode_staged=False,
                        )
                    node.publish_ready(False, repeats=1)
                    continue

                try:
                    start_recording(
                        f"收到 {inference_record_topic}=true 且 {start_topic}=true，开启本条采集",
                        event,
                        automation_staged_enabled(),
                    )
                except Exception as exc:  # noqa: BLE001 - keep bridge alive after one failed cycle.
                    log(f"ERROR starting collection: {exc}")
                    set_status(
                        "error",
                        f"本条录制启动失败：{exc}",
                        last_event=event,
                        last_error=str(exc),
                        inference_record_active=inference_record_active,
                        state_machine_start_active=state_machine_start_active,
                        active_stage=current_stage,
                        episode_staged=episode_staged,
                    )
                    node.publish_ready(False)
                    phase = "idle"
                continue

            if event.startswith("stage:"):
                _, stage_text, topic = event.split(":", 2)
                stage_no = int(stage_text)
                if not episode_staged:
                    log(f"ignore staged event {event} while current episode is not staged")
                    set_status(
                        phase if phase != "idle" else "idle",
                        f"当前未按分阶段模式采集，已忽略 {topic}=true。",
                        last_event=f"stage{stage_no}",
                        active_stage=current_stage,
                        episode_staged=episode_staged,
                    )
                    continue
                if phase != "recording":
                    log(f"ignore staged event {event} while phase={phase}")
                    set_status(
                        phase,
                        f"当前状态为 {phase}，已忽略阶段事件 {topic}=true。",
                        last_event=f"stage{stage_no}",
                        active_stage=current_stage,
                        episode_staged=episode_staged,
                    )
                    continue
                if stage_no != current_stage:
                    log(f"ignore staged event {event}; expected stage {current_stage}")
                    set_status(
                        "recording",
                        f"收到阶段 {stage_no} 事件 {topic}=true，但当前等待阶段 {current_stage}，已忽略。",
                        last_event=f"stage{stage_no}",
                        active_stage=current_stage,
                        episode_staged=True,
                    )
                    continue
                if current_stage > 4:
                    log(f"ignore staged event {event}; waiting final end")
                    set_status(
                        "recording",
                        f"已进入阶段 5，等待 {end_topic}=true 保存，已忽略 {topic}=true。",
                        last_event=f"stage{stage_no}",
                        active_stage=current_stage,
                        episode_staged=True,
                    )
                    continue
                try:
                    mark_stage_boundary(stage_no, topic)
                except Exception as exc:  # noqa: BLE001
                    log(f"ERROR marking stage {stage_no}: {exc}")
                    set_status(
                        "error",
                        f"阶段 {stage_no} 切换失败：{exc}",
                        last_event=f"stage{stage_no}",
                        last_error=str(exc),
                        active_stage=current_stage,
                        episode_staged=True,
                    )
                    node.publish_ready(False)
                    phase = "recording"
                continue

            if event == "end":
                if phase in {"idle", "starting"}:
                    try:
                        status = http.status()
                    except Exception as exc:  # noqa: BLE001
                        log(f"end received while phase={phase}; status unavailable: {exc}")
                        set_status("error", f"收到结束信号但读取采集状态失败：{exc}", last_event="end", last_error=str(exc))
                        node.publish_ready(False)
                        phase = "idle"
                        continue
                    if not status.get("capture_running"):
                        log("end received but collection is not recording; " + status_summary(status))
                        set_status(
                            "idle",
                            f"收到 {end_topic}=true，但当前没有正在录制；等待 {inference_record_topic}=true 且 {start_topic}=true 开启本条采集。",
                            last_event="end",
                            inference_record_active=inference_record_active,
                            state_machine_start_active=state_machine_start_active,
                            active_stage=0,
                            completed_stages=0,
                            episode_staged=False,
                        )
                        node.publish_ready(False)
                        phase = "idle"
                        continue
                    phase = "recording"

                if phase == "saving":
                    log("ignore end while saving")
                    set_status("saving", "正在保存当前 episode，已忽略重复结束信号。", last_event="end")
                    continue

                try:
                    if episode_staged and current_stage < 5:
                        log(f"final end received before stage 5; current_stage={current_stage}")
                    saved_status = save_current_episode("end")
                    saved_message = saved_status.get("message")
                    next_episode = saved_status.get("episode")
                    set_status(
                        "idle",
                        f"保存完成，已切到 episode{next_episode}；等待 {inference_record_topic}=true 且 {start_topic}=true 开启下一条采集。",
                        last_event="end",
                        inference_record_active=inference_record_active,
                        state_machine_start_active=state_machine_start_active,
                        active_stage=0,
                        completed_stages=0,
                        episode_staged=False,
                    )
                    if saved_message:
                        log(f"save result message: {saved_message}")
                    node.publish_ready(False)
                    phase = "idle"
                except Exception as exc:  # noqa: BLE001
                    log(f"ERROR saving collection: {exc}")
                    set_status(
                        "error",
                        f"自动停止/保存失败：{exc}",
                        last_event="end",
                        last_error=str(exc),
                        active_stage=current_stage,
                        episode_staged=episode_staged,
                    )
                    node.publish_ready(False)
                    phase = "idle"
                continue
    finally:
        try:
            node.publish_ready(False, repeats=2)
        except Exception:
            pass
        node.destroy_node()
        if rclpy.ok():
            rclpy.shutdown()
    return 0


