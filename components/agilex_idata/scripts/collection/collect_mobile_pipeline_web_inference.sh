def module_unavailable(handler: BaseHTTPRequestHandler, name: str) -> None:
    body = json.dumps({"ok": False, "error": f"{name} module is disabled"}, ensure_ascii=False).encode("utf-8")
    handler.send_response(HTTPStatus.SERVICE_UNAVAILABLE)
    handler.send_header("Content-Type", "application/json; charset=utf-8")
    handler.send_header("Content-Length", str(len(body)))
    handler.send_header("Cache-Control", "no-store")
    handler.end_headers()
    handler.wfile.write(body)


def atomic_write_json(path: str, payload: dict) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = f"{path}.tmp"
    with open(tmp, "w", encoding="utf-8") as handle:
        json.dump(payload, handle, ensure_ascii=False)
    os.replace(tmp, path)


