#   bash scripts/collection/collect_mobile_pipeline_web_inference.sh [dataset_dir] [start_episode_index] [left_target] [right_target]
#   bash scripts/collection/collect_mobile_pipeline_web_inference.sh [start_episode_index]
#
# Open:
#   http://<robot-ip>:8848/
#
# The original collection controller is left unchanged and is started behind
