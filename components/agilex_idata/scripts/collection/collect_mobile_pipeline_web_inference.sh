                DATA_DIR_ARG="$1"
            elif [ -z "${LEFT_TARGET_ARG}" ]; then
                LEFT_TARGET_ARG="$1"
            elif [ -z "${RIGHT_TARGET_ARG}" ]; then
                RIGHT_TARGET_ARG="$1"
            else
                echo "[错误] 无法识别参数: $1" >&2
