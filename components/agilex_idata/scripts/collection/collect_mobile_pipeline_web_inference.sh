write_target_stage_preset() {
    is_truthy "${GENERATE_STAGE_PRESET_FROM_TARGETS}" || return 0
    mkdir -p "$(dirname "${STAGE_PRESET_INFO_JSON}")"
    python3 - \
        "${STAGE_PRESET_INFO_JSON}" \
        "${COLLECTION_ARM_MODE}" \
        "${TARGET_BOTTLE_A}" \
        "${TARGET_BOTTLE_B}" <<'PY'
import json
import os
import sys

path = sys.argv[1]
mode = sys.argv[2]
left_target = sys.argv[3]
right_target = sys.argv[4]

if mode == "dual":
    stages = [
        "Move chassis to shelf.",
        f"Grasp {left_target} with the left hand, then grasp {right_target} with the right hand.",
        "Move chassis to cart.",
        f"Place {left_target} into the cart with the left hand, then place {right_target} into the cart with the right hand.",
        "Move chassis to start.",
    ]
else:
    stages = [
        "Move chassis to shelf.",
        f"Grasp {left_target} with the left hand.",
        "Move chassis to cart.",
        f"Place {left_target} into the cart with the left hand.",
        "Move chassis to start.",
    ]

payload = {
    "mark": {
        "full-instructions-en": ["\n".join(stages)],
        "full-instructions-zh": ["\n".join(stages)],
        "segment-instructions": [
            {
                "description_en": [text],
                "description_zh": [text],
            }
            for text in stages
        ],
    }
}

os.makedirs(os.path.dirname(path), exist_ok=True)
tmp = f"{path}.tmp"
with open(tmp, "w", encoding="utf-8") as handle:
    json.dump(payload, handle, ensure_ascii=False, indent=2)
    handle.write("\n")
os.replace(tmp, path)
PY
}

find_free_port() {
    python3 - "$1" <<'PY'
import socket
import sys

start = int(sys.argv[1])
for port in range(start, start + 200):
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        try:
            sock.bind(("127.0.0.1", port))
        except OSError:
            continue
        print(port)
        raise SystemExit(0)
raise SystemExit(f"no free port from {start}")
PY
}

wait_for_port() {
    local port="$1"
    local label="$2"
    local timeout="${3:-30}"
    local connect_host="${4:-127.0.0.1}"
    python3 - "$port" "$label" "$timeout" "$connect_host" <<'PY'
import socket
import sys
import time

port = int(sys.argv[1])
label = sys.argv[2]
timeout = float(sys.argv[3])
host = sys.argv[4]
deadline = time.time() + timeout
last_error = None
while time.time() < deadline:
    try:
        with socket.create_connection((host, port), timeout=0.5):
            raise SystemExit(0)
    except OSError as exc:
        last_error = exc
        time.sleep(0.2)
raise SystemExit(f"{label} did not open {host}:{port}: {last_error}")
PY
}

print_web_urls() {
    local display_host="${WEB_PUBLIC_HOST:-${WEB_HOST}}"
    local local_host="${WEB_HOST}"
    local route_ip=""
    local candidate_ips=""
    if [ "${WEB_HOST}" = "0.0.0.0" ] || [ "${WEB_HOST}" = "::" ]; then
        local_host="127.0.0.1"
        if [ -z "${WEB_PUBLIC_HOST:-}" ]; then
            route_ip="$(ip route get 1.1.1.1 2>/dev/null | awk '{for (i=1; i<=NF; i++) if ($i == "src") {print $(i+1); exit}}')"
            display_host="${route_ip:-127.0.0.1}"
        fi
        candidate_ips="$(hostname -I 2>/dev/null | tr ' ' '\n' | sed '/^$/d' | paste -sd ' ' -)"
    fi
    echo ""
    echo "===== 统一数据网站已启动 ====="
    echo "本机访问: http://${local_host}:${WEB_PORT}/"
    echo "外部访问: http://${display_host}:${WEB_PORT}/"
    if [ -n "${candidate_ips}" ]; then
        echo "本机 IP 候选: ${candidate_ips}"
    fi
    echo "采集模块日志: ${COLLECTION_LOG}"
    echo "处理模块日志: ${PIPELINE_LOG}"
    if is_truthy "${VISUALIZER_ENABLE}"; then
        echo "可视化模块日志: ${VISUALIZER_LOG}"
    fi
    if is_truthy "${STATE_MACHINE_BRIDGE_ENABLE}" && is_truthy "${COLLECTION_ENABLE}"; then
        echo "状态机桥接日志: ${STATE_MACHINE_BRIDGE_LOG}"
    fi
    echo "网关日志: ${GATEWAY_LOG}"
}

start_collection() {
    is_truthy "${COLLECTION_ENABLE}" || return 0
    [ -f "${COLLECTION_SCRIPT}" ] || die "找不到采集脚本: ${COLLECTION_SCRIPT}"
    local port
    port="${COLLECTION_WEB_PORT:-}"
    if [ -z "${port}" ] || [ "${port}" = "auto" ]; then
        port="$(find_free_port "$((WEB_PORT + 1))")"
    fi
    COLLECTION_WEB_PORT="${port}"
    COLLECTION_URL="http://127.0.0.1:${COLLECTION_WEB_PORT}"
    log "启动采集模块: ${COLLECTION_URL}"
    local cmd=(
        env
        WEB_HOST=127.0.0.1
        WEB_PORT="${COLLECTION_WEB_PORT}"
        DATA_DIR="${DATA_DIR}"
        EPISODE_INDEX="${START_INDEX}"
        STAGED_CAPTURE="${COLLECTION_STAGED_CAPTURE_DEFAULT}"
        STAGE_PRESET_INFO_JSON="${STAGE_PRESET_INFO_JSON}"
        TARGET_BOTTLE_A="${TARGET_BOTTLE_A}"
        TARGET_BOTTLE_B="${TARGET_BOTTLE_B}"
        TARGET_BOTTLE_A_ZH="${TARGET_BOTTLE_A_ZH}"
        TARGET_BOTTLE_B_ZH="${TARGET_BOTTLE_B_ZH}"
        COLLECTION_SCENE_INVENTORY_JSON="${COLLECTION_SCENE_INVENTORY_JSON}"
        COLLECTION_AUTO_GRADE="${COLLECTION_AUTO_GRADE}"
        RAW_MCAP_ONLY="${RAW_MCAP_ONLY:-1}"
        RUN_CONVERT="${RUN_CONVERT:-0}"
        RUN_QC="${RUN_QC:-0}"
        RUN_LEROBOT="0"
        BACKGROUND_PROCESSING="0"
        WEB_RUNTIME_DIR="${WEB_RUNTIME_DIR:-${LOG_ROOT}/inference_collector_runtime}"
        bash "${COLLECTION_SCRIPT}" "${START_INDEX}"
    )
    if command -v setsid >/dev/null 2>&1; then
        setsid "${cmd[@]}" >"${COLLECTION_LOG}" 2>&1 &
    else
        "${cmd[@]}" >"${COLLECTION_LOG}" 2>&1 &
    fi
    COLLECTION_PID="$!"
    if ! wait_for_port "${COLLECTION_WEB_PORT}" "collection web" 35; then
        tail -120 "${COLLECTION_LOG}" >&2 || true
        die "采集模块启动失败"
    fi
}

start_pipeline() {
    is_truthy "${PIPELINE_ENABLE}" || return 0
    [ -f "${PIPELINE_APP}" ] || die "找不到流水线网页: ${PIPELINE_APP}"
    local port
    port="${PIPELINE_WEB_PORT:-}"
    if [ -z "${port}" ] || [ "${port}" = "auto" ]; then
        port="$(find_free_port 8890)"
        if [ "${port}" = "${COLLECTION_WEB_PORT:-}" ]; then
            port="$(find_free_port "$((port + 1))")"
        fi
    fi
    PIPELINE_WEB_PORT="${port}"
    PIPELINE_URL="http://127.0.0.1:${PIPELINE_WEB_PORT}"
    local pipeline_data_root pipeline_lerobot_python
    pipeline_data_root="${PIPELINE_DATA_ROOT:-}"
    pipeline_lerobot_python="${LEROBOT_PYTHON:-}"
    if [ -z "${pipeline_lerobot_python}" ]; then
        if [ -x /home/agilex/openpi/.venv/bin/python ]; then
            pipeline_lerobot_python=/home/agilex/openpi/.venv/bin/python
        elif [ -x /home/agilex/miniforge3/envs/lerobot/bin/python ]; then
            pipeline_lerobot_python=/home/agilex/miniforge3/envs/lerobot/bin/python
        else
            pipeline_lerobot_python=python3
        fi
    fi
    log "启动数据处理/质检模块: ${PIPELINE_URL}"
    env \
        PIPELINE_DATA_ROOT="${pipeline_data_root}" \
        PIPELINE_DEFAULT_MCAP_PATH="${PIPELINE_DEFAULT_MCAP_PATH:-}" \
        PIPELINE_DEFAULT_DATASET_NAME="${PIPELINE_DEFAULT_DATASET_NAME:-}" \
        PIPELINE_DEFAULT_HDF5_ROOT="${PIPELINE_DEFAULT_HDF5_ROOT:-}" \
        PIPELINE_DEFAULT_QC_ROOT="${PIPELINE_DEFAULT_QC_ROOT:-}" \
        PIPELINE_DEFAULT_LEROBOT_ROOT="${PIPELINE_DEFAULT_LEROBOT_ROOT:-}" \
        PIPELINE_DEFAULT_ROBOT_TYPE="${PIPELINE_DEFAULT_ROBOT_TYPE:-}" \
        PIPELINE_DEFAULT_TASK_TEXT="${PIPELINE_DEFAULT_TASK_TEXT:-}" \
        PIPELINE_DEFAULT_REPO_ID="${PIPELINE_DEFAULT_REPO_ID:-}" \
        PIPELINE_DEFAULT_CONVERT_JOBS="${PIPELINE_DEFAULT_CONVERT_JOBS:-}" \
        PIPELINE_DEFAULT_USE_DOCKER="${PIPELINE_DEFAULT_USE_DOCKER:-0}" \
        PIPELINE_FAILURE_ANNOTATIONS_JSON="${FAILURE_ANNOTATIONS_JSON}" \
        LEROBOT_PYTHON="${pipeline_lerobot_python}" \
        python3 -u "${PIPELINE_APP}" --host 127.0.0.1 --port "${PIPELINE_WEB_PORT}" >"${PIPELINE_LOG}" 2>&1 &
    PIPELINE_PID="$!"
    if ! wait_for_port "${PIPELINE_WEB_PORT}" "pipeline web" 20; then
        tail -120 "${PIPELINE_LOG}" >&2 || true
        die "数据处理/质检模块启动失败"
    fi
}

