            shift 2
            ;;
        --right-target|--target-b|--bottle-b)
            [ "$#" -ge 2 ] || {
                echo "[错误] $1 需要右臂物品参数" >&2
                exit 1
            }
            RIGHT_TARGET_ARG="$2"
            shift 2
            ;;
        -i|--start-index)
            [ "$#" -ge 2 ] || {
                echo "[错误] $1 需要 episode 起始编号" >&2
                exit 1
