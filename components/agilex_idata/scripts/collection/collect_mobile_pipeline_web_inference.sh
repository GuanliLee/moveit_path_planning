terminate_process() {
    local pid="$1"
    local signal="$2"
    if [ -z "${pid}" ] || ! kill -0 "${pid}" >/dev/null 2>&1; then
        return 0
    fi
    kill "-${signal}" "-${pid}" >/dev/null 2>&1 || kill "-${signal}" "${pid}" >/dev/null 2>&1 || true
}

wait_process_exit() {
    local pid="$1"
    local tenths="${2:-30}"
    local waited=0
    while [ "${waited}" -lt "${tenths}" ]; do
        if ! kill -0 "${pid}" >/dev/null 2>&1; then
            wait "${pid}" 2>/dev/null || true
            return 0
        fi
        sleep 0.1
        waited=$((waited + 1))
    done
    return 1
}

stop_child() {
    local pid="$1"
    [ -n "${pid}" ] || return 0
    if ! kill -0 "${pid}" >/dev/null 2>&1; then
        wait "${pid}" 2>/dev/null || true
        return 0
    fi
    # Bash background jobs may inherit SIGINT=ignore. TERM is trapped by the
    # collection controller and handled by rclpy, and reliably stops Web jobs.
    terminate_process "${pid}" TERM
    wait_process_exit "${pid}" 200 && return 0
    terminate_process "${pid}" KILL
    wait "${pid}" 2>/dev/null || true
}

stop_port_listeners() {
    local port="$1"
    [ -n "${port:-}" ] || return 0
    local pid
    while IFS= read -r pid; do
        [ -n "${pid}" ] || continue
        stop_child "${pid}"
    done < <(lsof -ti TCP:"${port}" -sTCP:LISTEN 2>/dev/null || true)
}

