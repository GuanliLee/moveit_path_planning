class CollectionHttp:
    def __init__(self, base_url: str):
        parsed = urlparse(base_url)
        if parsed.scheme != "http" or not parsed.hostname or not parsed.port:
            raise ValueError(f"unsupported collection URL: {base_url}")
        self.host = parsed.hostname
        self.port = parsed.port

    def request(
        self,
        method: str,
        path: str,
        timeout: float = 10.0,
        *,
        body: bytes | None = None,
        headers: dict[str, str] | None = None,
    ) -> tuple[int, bytes]:
        conn = http.client.HTTPConnection(self.host, self.port, timeout=timeout)
        try:
            request_headers = {"Connection": "close"}
            if headers:
                request_headers.update(headers)
            if body is not None:
                request_headers["Content-Length"] = str(len(body))
            conn.request(method, path, body=body, headers=request_headers)
            resp = conn.getresponse()
            body = resp.read()
            if resp.status >= 400:
                raise RuntimeError(f"{method} {path} returned {resp.status}: {body[:300]!r}")
            return resp.status, body
        finally:
            conn.close()

    def status(self) -> dict:
        _, body = self.request("GET", "/status", timeout=5.0)
        return json.loads(body.decode("utf-8") or "{}")

    def post(self, path: str) -> None:
        self.request("POST", path, timeout=10.0)

    def post_json(self, path: str, payload: dict) -> None:
        body = json.dumps(payload, ensure_ascii=False).encode("utf-8")
        self.request(
            "POST",
            path,
            timeout=10.0,
            body=body,
            headers={"Content-Type": "application/json; charset=utf-8"},
        )


class StateMachineBridge(Node):
    def __init__(self):
        super().__init__("data_collection_state_machine_bridge")
        self.events: queue.SimpleQueue[str | tuple[str, str, str]] = queue.SimpleQueue()
        self.event_context = ("grasp", "idle")
        ready_qos = QoSProfile(depth=1)
        ready_qos.reliability = ReliabilityPolicy.RELIABLE
        ready_qos.durability = DurabilityPolicy.TRANSIENT_LOCAL
        self.ready_pub = self.create_publisher(Bool, ready_topic, ready_qos)
        save_success_qos = QoSProfile(depth=1)
        save_success_qos.reliability = ReliabilityPolicy.RELIABLE
        save_success_qos.durability = DurabilityPolicy.TRANSIENT_LOCAL
        self.save_success_pub = self.create_publisher(Bool, save_success_topic, save_success_qos)
        self.save_success_state: bool | None = None
        self.create_subscription(Bool, start_topic, self._on_start, 10)
        self.create_subscription(Bool, end_topic, self._on_end, 10)
        if two_phase_enabled:
            self.create_subscription(Bool, grasp_end_topic, self._on_grasp_end, 10)
            self.create_subscription(Bool, place_start_topic, self._on_place_start, 10)
        if not two_phase_enabled:
            for stage_no, topics in stage_topic_groups:
                for topic in topics:
                    self.create_subscription(
                        Bool,
                        topic,
                        lambda msg, stage_no=stage_no, topic=topic: self._on_stage(msg, stage_no, topic),
                        10,
                    )

    def _on_start(self, msg: Bool) -> None:
        if msg.data:
            self._put_event("start")

    def _on_end(self, msg: Bool) -> None:
        if msg.data:
            self._put_event("end")

    def _on_grasp_end(self, msg: Bool) -> None:
        if msg.data:
            self._put_event("grasp_end")

    def _on_place_start(self, msg: Bool) -> None:
        if msg.data:
            self._put_event("place_start")

    def _on_stage(self, msg: Bool, stage_no: int, topic: str) -> None:
        if msg.data:
            self.events.put(f"stage:{stage_no}:{topic}")

    def set_event_context(self, capture_phase: str, runtime_phase: str) -> None:
        self.event_context = (capture_phase, runtime_phase)

    def _put_event(self, event: str) -> None:
        if two_phase_enabled:
            capture_phase, runtime_phase = self.event_context
            self.events.put((event, capture_phase, runtime_phase))
        else:
            self.events.put(event)

    def publish_ready(self, value: bool, repeats: int | None = None) -> None:
        msg = Bool()
        msg.data = bool(value)
        count = publish_repeats if repeats is None else max(1, int(repeats))
        for _ in range(count):
            try:
                self.ready_pub.publish(msg)
            except Exception:
                if ros_publish_error_is_shutdown():
                    return
                raise
            if not two_phase_enabled:
                try:
                    rclpy.spin_once(self, timeout_sec=0.0)
                except ExternalShutdownException:
                    return
            time.sleep(0.05)

    def publish_save_success(self, value: bool, repeats: int | None = None) -> None:
        value = bool(value)
        if self.save_success_state == value:
            return
        self.save_success_state = value
        msg = Bool()
        msg.data = value
        count = publish_repeats if repeats is None else max(1, int(repeats))
        for _ in range(count):
            try:
                self.save_success_pub.publish(msg)
            except Exception:
                if ros_publish_error_is_shutdown():
                    return
                raise
            if not two_phase_enabled:
                try:
                    rclpy.spin_once(self, timeout_sec=0.0)
                except ExternalShutdownException:
                    return
            time.sleep(0.05)


def wait_for_status(http: CollectionHttp, predicate, timeout: float, label: str) -> dict:
    deadline = time.monotonic() + timeout
    last_status: dict = {}
    while rclpy.ok() and time.monotonic() < deadline:
        last_status = http.status()
        if predicate(last_status):
            return last_status
        time.sleep(max(0.05, poll_interval))
    raise TimeoutError(f"timed out waiting for {label}; last status={last_status}")


def validated_initial_episode(status: dict) -> int:
    value = status.get("episode")
    if isinstance(value, bool):
        raise ValueError(f"initial status has invalid episode: {value!r}")
    if isinstance(value, int):
        episode = value
    elif isinstance(value, str) and value.strip().isdigit():
        episode = int(value.strip())
    else:
        raise ValueError(f"initial status has no usable episode: {value!r}")
    if episode < 0:
        raise ValueError(f"initial status has negative episode: {episode}")
    return episode


def wait_for_initial_status(
    http: CollectionHttp,
    *,
    timeout: float,
    poll_interval: float,
) -> dict:
    deadline = time.monotonic() + timeout
    last_error: Exception | None = None
    while time.monotonic() < deadline:
        try:
            status = http.status()
            validated_initial_episode(status)
            return status
        except Exception as exc:  # noqa: BLE001 - retry transient collection startup failures.
            last_error = exc
            time.sleep(max(0.01, poll_interval))
    raise TimeoutError(f"timed out waiting for initial collection status: {last_error}")


def discard_two_phase_transition_events(
    node: StateMachineBridge,
    *,
    quiet_period: float,
) -> list[str | tuple[str, str, str]]:
    """Drain callbacks received while a reviewed target switch is settling."""
    quiet_period = max(0.01, float(quiet_period))
    quiet_deadline = time.monotonic() + quiet_period
    hard_deadline = time.monotonic() + max(0.5, quiet_period * 5)
    discarded: list[str | tuple[str, str, str]] = []
    while time.monotonic() < quiet_deadline:
        try:
            event = node.events.get_nowait()
        except queue.Empty:
            remaining = quiet_deadline - time.monotonic()
            if remaining > 0:
                time.sleep(min(0.01, remaining))
            continue
        discarded.append(event)
        quiet_deadline = min(time.monotonic() + quiet_period, hard_deadline)
    return discarded


def spin_ros_executor(executor: SingleThreadedExecutor) -> None:
    try:
        executor.spin()
    except ExternalShutdownException:
        pass


def status_summary(status: dict) -> str:
    return (
        f"state={status.get('state')!r}, "
        f"episode={status.get('episode')!r}, "
        f"capture_running={status.get('capture_running')!r}, "
        f"message={status.get('message')!r}"
    )


def is_recording_status(status: dict) -> bool:
    return bool(status.get("capture_running")) and str(status.get("state", "")).lower() == "recording"


def episode_changed(status: dict, previous_episode) -> bool:
    if previous_episode is None:
        return True
    return str(status.get("episode")) != str(previous_episode)


def save_review_finished(status: dict, saved_episode) -> bool:
    return episode_changed(status, saved_episode) or not bool(status.get("quality_review_pending"))


def reviewed_save_success_episode(status: dict) -> str:
    if bool(status.get("capture_running")) or bool(status.get("quality_review_pending")):
        return ""
    saved_episode = str(status.get("last_saved_episode", "")).strip()
    current_episode = str(status.get("episode", "")).strip()
    if not saved_episode.isdigit() or not current_episode.isdigit():
        return ""
    if int(current_episode) <= int(saved_episode):
        return ""
    return saved_episode


def save_success_transition(
    status: dict,
    *,
    baseline_initialized: bool,
    armed: bool,
) -> tuple[bool, bool, bool | None]:
    active_cycle = bool(status.get("capture_running")) or bool(status.get("quality_review_pending"))
    if not baseline_initialized:
        return True, active_cycle, False
    if active_cycle:
        return True, True, False
    if armed and reviewed_save_success_episode(status):
        return True, False, True
    if not str(status.get("last_saved_episode", "")).strip():
        return True, False, False
    return True, armed, None


def collection_config_payload(
    status: dict,
    staged: bool,
    *,
    data_dir: str | None = None,
    episode_index: int | str | None = None,
) -> dict:
    current_data_dir = str(status.get("data_dir", "")).strip()
    target_data_dir = current_data_dir if data_dir is None else str(data_dir).strip()
    target_episode = status.get("episode", 0) if episode_index is None else episode_index
    lerobot_target_dir = str(status.get("lerobot_target_dir", "")).strip()
    lerobot_dataset_name = str(status.get("lerobot_dataset_name", "")).strip()
    if target_data_dir != current_data_dir:
        current_default_lerobot = os.path.join(current_data_dir, "lerobot") if current_data_dir else ""
        if not lerobot_target_dir or (
            current_default_lerobot
            and os.path.normpath(lerobot_target_dir) == os.path.normpath(current_default_lerobot)
        ):
            lerobot_target_dir = os.path.join(target_data_dir, "lerobot")
        current_default_name = (
            f"{os.path.basename(os.path.normpath(current_data_dir))}_aloha_mobile"
            if current_data_dir
            else ""
        )
        if not lerobot_dataset_name or lerobot_dataset_name == current_default_name:
            lerobot_dataset_name = f"{os.path.basename(os.path.normpath(target_data_dir))}_aloha_mobile"
    return {
        "data_dir": target_data_dir,
        "episode_index": str(target_episode),
        "with_base": bool(status.get("with_base", True)),
        "staged_capture": bool(staged),
        "auto_save_on_preset": False if staged else bool(status.get("auto_save_on_preset", False)),
        "run_convert": bool(status.get("run_convert", True)),
        "run_qc": bool(status.get("run_qc", True)),
        "run_lerobot": bool(status.get("run_lerobot", False)),
        "background_processing": bool(status.get("background_processing", True)),
        "preset_info_json": status.get("preset_info_json", ""),
        "lerobot_target_dir": lerobot_target_dir,
        "lerobot_dataset_name": lerobot_dataset_name,
    }


def configure_collection_for_mode(http: CollectionHttp, staged: bool) -> dict:
    status = http.status()
    if status.get("capture_running"):
        if bool(status.get("staged_capture")) != staged:
            raise RuntimeError(
                "collection is already recording with staged_capture="
                f"{status.get('staged_capture')}; cannot switch to {staged}"
            )
        return status
    http.post_json("/config", collection_config_payload(status, staged))
    return wait_for_status(
        http,
        lambda item: (
            bool(item.get("staged_capture")) == staged
            and (not staged or not bool(item.get("auto_save_on_preset")))
        ),
        8.0,
        f"collection config staged_capture={staged}",
    )


def configure_collection_for_target(
    http: CollectionHttp,
    *,
    data_dir: str,
    episode_index: int,
) -> dict:
    status = http.status()
    if status.get("capture_running") or status.get("quality_review_pending"):
        raise RuntimeError("cannot switch collection target while capture or review is active")
    target_dir = os.path.normpath(data_dir)
    if (
        os.path.normpath(str(status.get("data_dir", ""))) == target_dir
        and str(status.get("episode")) == str(episode_index)
        and not bool(status.get("staged_capture"))
    ):
        return status
    http.post_json(
        "/config",
        collection_config_payload(
            status,
            False,
            data_dir=target_dir,
            episode_index=episode_index,
        ),
    )
    return wait_for_status(
        http,
        lambda item: (
            not bool(item.get("capture_running"))
            and not bool(item.get("quality_review_pending"))
            and not bool(item.get("staged_capture"))
            and os.path.normpath(str(item.get("data_dir", ""))) == target_dir
            and str(item.get("episode")) == str(episode_index)
        ),
        8.0,
        f"collection target {target_dir}/episode{episode_index}",
    )


def expected_stage_topic(stage_no: int) -> str:
    for candidate_no, topics in stage_topic_groups:
        if candidate_no == stage_no and topics:
            return topics[0]
    return ""


def as_int(value, default: int = 0) -> int:
    try:
        return int(value)
    except (TypeError, ValueError):
        return default


def main() -> int:
    http = CollectionHttp(collection_url)
    initial_collection_status = None
    if two_phase_enabled:
        try:
            initial_collection_status = wait_for_initial_status(
                http,
                timeout=start_timeout,
                poll_interval=poll_interval,
            )
        except Exception as exc:  # noqa: BLE001 - leave a durable diagnostic before exiting.
            log(f"initial collection status unavailable: {exc}")
            set_status(
                "error",
                f"抓取+放置模式无法读取初始采集状态：{exc}",
                last_error=str(exc),
                capture_phase="grasp",
                logical_episode="",
            )
            return 1
    rclpy.init()
    node = StateMachineBridge()
    ros_executor: SingleThreadedExecutor | None = None
    ros_spin_thread: threading.Thread | None = None
    if two_phase_enabled:
        ros_executor = SingleThreadedExecutor()
        ros_executor.add_node(node)
        ros_spin_thread = threading.Thread(
            target=spin_ros_executor,
            args=(ros_executor,),
            name="grasp-place-ros-executor",
            daemon=True,
        )
        ros_spin_thread.start()
    if initial_collection_status is None:
        try:
            initial_collection_status = http.status()
        except Exception as exc:  # noqa: BLE001
            log(f"initial collection status unavailable: {exc}")
    save_success_baseline_initialized = initial_collection_status is not None
    save_success_armed = bool(
        initial_collection_status
        and (
            initial_collection_status.get("capture_running")
            or initial_collection_status.get("quality_review_pending")
        )
    )
    last_status_poll_at = 0.0
    node.publish_save_success(False, repeats=2)
    phase = "idle"
    enabled = automation_enabled()
    staged_enabled = automation_staged_enabled()
    episode_staged = False
    current_stage = 0
    capture_phase = "grasp"
    logical_episode = (
        validated_initial_episode(initial_collection_status)
        if two_phase_enabled
        else as_int(
            initial_collection_status.get("episode") if initial_collection_status else 0,
            0,
        )
    )
    pending_review_episode: int | None = None
    pending_review_phase = ""
    review_started_at = 0.0
    review_timeout_reported = False
    review_completion_observed = False
    resolved_review_transition: tuple[str, str, int, str] | None = None
    pending_place_start = False

    def sync_event_context() -> None:
        node.set_event_context(capture_phase, phase)

    sync_event_context()

    def two_phase_status_fields() -> dict:
        if not two_phase_enabled:
            return {}
        return {
            "capture_phase": capture_phase,
            "logical_episode": logical_episode,
            "pending_place_start": pending_place_start,
        }

    def enabled_idle_message() -> str:
        if two_phase_enabled:
            if capture_phase == "place":
                return (
                    f"episode{logical_episode} 抓取数据已完成评级；"
                    f"等待 {place_start_topic}=true 开启放置录制。"
                )
            return f"等待 {start_topic}=true 开启 episode{logical_episode} 抓取录制。"
        if automation_staged_enabled():
            return f"自动监听已启用；分阶段模式已选择，等待 {start_topic}=true 开启第一阶段。"
        return f"自动监听已启用；未开始录制，等待 {start_topic}=true 开启本条采集。"

    def recording_wait_message(episode) -> str:
        if two_phase_enabled:
            if capture_phase == "grasp":
                return (
                    f"episode{episode} 正在录制抓取数据；已发布 {ready_topic}=true，"
                    f"等待 {grasp_end_topic}=true 保存。"
                )
            return (
                f"episode{episode} 正在录制放置数据；已发布 {ready_topic}=true，"
                f"等待 {end_topic}=true 保存。"
            )
        if episode_staged:
            if current_stage <= 4:
                topic = expected_stage_topic(current_stage)
                return f"episode{episode} 正在分阶段采集：阶段 {current_stage}；等待 {topic}=true。"
            return f"episode{episode} 正在分阶段采集：阶段 5；等待 {end_topic}=true 保存。"
        return f"episode{episode} 已确认进入 recording；已发布 {ready_topic}=true，等待 {end_topic}=true。"

    def observe_collection_status(status: dict) -> None:
        nonlocal save_success_baseline_initialized, save_success_armed
        save_success_baseline_initialized, save_success_armed, publish_value = save_success_transition(
            status,
            baseline_initialized=save_success_baseline_initialized,
            armed=save_success_armed,
        )
        if publish_value is not None:
            node.publish_save_success(publish_value)

    def start_recording(reason: str, last_event: str, staged_for_episode: bool) -> None:
        nonlocal phase, episode_staged, current_stage
        nonlocal save_success_baseline_initialized, save_success_armed
        phase = "starting"
        sync_event_context()
        save_success_baseline_initialized = True
        save_success_armed = True
        node.publish_save_success(False)
        episode_staged = bool(staged_for_episode)
        current_stage = 1 if episode_staged else 0
        mode_text = "分阶段" if episode_staged else "不分阶段"
        set_status(
            "starting",
            f"{reason}，正在按{mode_text}模式启动本条录制；尚未发布 {ready_topic}=true。",
            last_event=last_event,
            active_stage=current_stage,
            completed_stages=0,
            episode_staged=episode_staged,
            **two_phase_status_fields(),
        )
        node.publish_ready(False, repeats=2)
        status = configure_collection_for_mode(http, episode_staged)
        log(f"start recording requested; mode={mode_text}; current " + status_summary(status))
        episode = status.get("episode")
        if is_recording_status(status):
            log("collection was already recording; " + status_summary(status))
            current_stage = as_int(status.get("current_stage"), current_stage) if episode_staged else 0
            set_status(
                "recording",
                recording_wait_message(episode),
                last_event=last_event,
                active_stage=current_stage,
                completed_stages=as_int(status.get("completed_stages"), 0),
                episode_staged=episode_staged,
                **two_phase_status_fields(),
            )
            phase = "recording"
            sync_event_context()
            node.publish_ready(True)
            return
        set_status(
            "starting",
            f"{reason}，正在按{mode_text}模式启动 episode{episode} 录制；尚未发布 {ready_topic}=true。",
            last_event=last_event,
            active_stage=current_stage,
            completed_stages=0,
            episode_staged=episode_staged,
            **two_phase_status_fields(),
        )
        if not status.get("capture_running"):
            http.post("/start")
        status = wait_for_status(
            http,
            is_recording_status,
            start_timeout,
            "collection to enter recording state",
        )
        log("collection recording; " + status_summary(status))
        episode = status.get("episode")
        current_stage = as_int(status.get("current_stage"), current_stage) if episode_staged else 0
        set_status(
            "recording",
            recording_wait_message(episode),
            last_event=last_event,
            active_stage=current_stage,
            completed_stages=as_int(status.get("completed_stages"), 0),
            episode_staged=episode_staged,
            **two_phase_status_fields(),
        )
        phase = "recording"
        sync_event_context()
        node.publish_ready(True)

    def mark_stage_boundary(stage_no: int, topic: str) -> dict:
        nonlocal current_stage
        status = http.status()
        if not is_recording_status(status):
            raise RuntimeError(f"stage {stage_no} received while collection is not recording; {status_summary(status)}")
        episode = status.get("episode")
        set_status(
            "recording",
            f"收到 {topic}=true，正在结束阶段 {stage_no} 并进入阶段 {stage_no + 1}。",
            last_event=f"stage{stage_no}",
            active_stage=stage_no,
            completed_stages=as_int(status.get("completed_stages"), 0),
