    local cmd=(
        env
        WEB_HOST=127.0.0.1
        WEB_PORT="${COLLECTION_WEB_PORT}"
        DATA_DIR="${DATA_DIR}"
        EPISODE_INDEX="${START_INDEX}"
        STAGED_CAPTURE="${COLLECTION_STAGED_CAPTURE_DEFAULT}"
        STAGE_PRESET_INFO_JSON="${STAGE_PRESET_INFO_JSON}"
        TARGET_BOTTLE_A="${TARGET_BOTTLE_A}"
        TARGET_BOTTLE_B="${TARGET_BOTTLE_B}"
        TARGET_BOTTLE_A_ZH="${TARGET_BOTTLE_A_ZH}"
        TARGET_BOTTLE_B_ZH="${TARGET_BOTTLE_B_ZH}"
        MOBILE_YAML="${MOBILE_YAML}"
        COLLECTION_SCENE_INVENTORY_JSON="${COLLECTION_SCENE_INVENTORY_JSON}"
        COLLECTION_AUTO_GRADE="${AUTO_GRADE}"
        RAW_MCAP_ONLY="${RAW_MCAP_ONLY:-1}"
        RUN_CONVERT="${RUN_CONVERT:-0}"
        RUN_QC="${RUN_QC:-0}"
        RUN_LEROBOT="0"
        BACKGROUND_PROCESSING="0"
        WEB_RUNTIME_DIR="${WEB_RUNTIME_DIR:-${LOG_ROOT}/collector_runtime}"
