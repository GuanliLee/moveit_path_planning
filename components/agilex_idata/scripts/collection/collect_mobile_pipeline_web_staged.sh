class Handler(BaseHTTPRequestHandler):
    server_version = "UnifiedAlohaDataWeb/1.0"

    def send_json(self, status: int, payload: dict) -> None:
        body = json.dumps(payload, ensure_ascii=False).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        if self.command != "HEAD":
            self.wfile.write(body)

    def do_GET(self) -> None:
        self.handle_request(send_body=True)

    def do_POST(self) -> None:
        self.handle_request(send_body=True)

    def do_HEAD(self) -> None:
        self.handle_request(send_body=False)

    def do_OPTIONS(self) -> None:
        self.send_response(204)
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Access-Control-Allow-Methods", "GET, POST, HEAD, OPTIONS")
        self.send_header("Access-Control-Allow-Headers", "Content-Type, Range")
        self.end_headers()

    def handle_request(self, send_body: bool = True) -> None:
        parsed = urlparse(self.path)
        if parsed.path in {"/", "/index.html"}:
            body = page().encode("utf-8")
            self.send_response(200)
            self.send_header("Content-Type", "text/html; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            if send_body and self.command != "HEAD":
                self.wfile.write(body)
            return
        if parsed.path == "/favicon.ico":
            self.send_response(204)
            self.end_headers()
            return
        if parsed.path == "/automation/status":
            self.send_json(200, read_automation_state())
            return
        if parsed.path == "/automation/start":
            if self.command != "POST":
                self.send_json(405, {"ok": False, "error": "POST required"})
                return
            self.send_json(202, {"ok": True, **set_automation_state(True)})
            return
        if parsed.path == "/automation/stop":
            if self.command != "POST":
                self.send_json(405, {"ok": False, "error": "POST required"})
                return
            self.send_json(202, {"ok": True, **set_automation_state(False)})
            return
        if parsed.path == "/automation/staged":
            if self.command != "POST":
                self.send_json(405, {"ok": False, "error": "POST required"})
                return
            try:
                payload = read_json_body(self)
            except json.JSONDecodeError as exc:
                self.send_json(400, {"ok": False, "error": str(exc)})
                return
            self.send_json(202, {"ok": True, **set_staged_automation_state(bool(payload.get("enabled", False)))})
            return

        backend, target = route_backend(parsed)
        if backend == "collection":
            if not collection_enabled:
                module_unavailable(self, "collection")
                return
            proxy(self, collection_url, with_query(target or "/", parsed.query), send_body=send_body)
            if self.command == "POST" and (target or "").rstrip("/") in {"/exit", "/quit"}:
                threading.Thread(target=self.server.shutdown, daemon=True).start()
            return
        if backend == "pipeline":
            if not pipeline_enabled:
                module_unavailable(self, "pipeline")
                return
            proxy(self, pipeline_url, with_query(target or "/", parsed.query), send_body=send_body)
            return
        if backend == "visualizer":
            if not visualizer_enabled:
                module_unavailable(self, "visualizer")
                return
            proxy(self, visualizer_url, with_query(target or "/", parsed.query), send_body=send_body)
            return

        payload = json.dumps({"ok": False, "error": "unknown route"}, ensure_ascii=False).encode("utf-8")
        self.send_response(404)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(payload)))
        self.end_headers()
        self.wfile.write(payload)

    def log_message(self, fmt: str, *args) -> None:
        sys.stderr.write("[%s] %s\n" % (time.strftime("%F %T"), fmt % args))


