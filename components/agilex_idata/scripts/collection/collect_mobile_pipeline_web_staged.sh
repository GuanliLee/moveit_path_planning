def read_json_body(handler: BaseHTTPRequestHandler) -> dict:
    length = int(handler.headers.get("Content-Length") or 0)
    if length <= 0:
        return {}
    body = handler.rfile.read(min(length, 65536)).decode("utf-8")
    if not body.strip():
        return {}
    return json.loads(body)


def copy_request_headers(handler: BaseHTTPRequestHandler) -> dict[str, str]:
    headers: dict[str, str] = {}
    for key, value in handler.headers.items():
        lower = key.lower()
        if lower in HOP_BY_HOP_HEADERS or lower == "host":
            continue
        headers[key] = value
    return headers


def proxy(handler: BaseHTTPRequestHandler, base_url: str, target_path: str, send_body: bool = True) -> None:
    parsed_base = urlparse(base_url)
    body = b""
    if handler.command in {"POST", "PUT", "PATCH"}:
        length = int(handler.headers.get("Content-Length") or 0)
        body = handler.rfile.read(length) if length > 0 else b""
    headers = copy_request_headers(handler)
    if body and "Content-Length" not in headers:
        headers["Content-Length"] = str(len(body))
    conn = http.client.HTTPConnection(parsed_base.hostname, parsed_base.port, timeout=300)
    try:
        conn.request(handler.command, target_path, body=body, headers=headers)
        resp = conn.getresponse()
        handler.send_response(resp.status, resp.reason)
        for key, value in resp.getheaders():
            if key.lower() in HOP_BY_HOP_HEADERS:
                continue
            handler.send_header(key, value)
        handler.send_header("X-Unified-Gateway", "1")
        handler.end_headers()
        if send_body and handler.command != "HEAD":
            while True:
                chunk = resp.read(64 * 1024)
                if not chunk:
                    break
                handler.wfile.write(chunk)
    except Exception as exc:
        payload = json.dumps({"ok": False, "error": str(exc)}, ensure_ascii=False).encode("utf-8")
        handler.send_response(HTTPStatus.BAD_GATEWAY)
        handler.send_header("Content-Type", "application/json; charset=utf-8")
        handler.send_header("Content-Length", str(len(payload)))
        handler.end_headers()
        handler.wfile.write(payload)
    finally:
        conn.close()


def strip_prefix(path: str, prefix: str) -> str:
    if path == prefix.rstrip("/"):
        return "/"
    stripped = path[len(prefix.rstrip("/")) :]
    return stripped or "/"


def with_query(path: str, query: str) -> str:
    return path + (("?" + query) if query else "")


def route_backend(parsed) -> tuple[str, str] | tuple[None, None]:
    path = parsed.path.rstrip("/") or "/"
    raw_path = parsed.path or "/"
    if raw_path.startswith("/collection/") or path == "/collection":
        return "collection", strip_prefix(raw_path, "/collection")
    if raw_path.startswith("/pipeline/") or path == "/pipeline":
        return "pipeline", strip_prefix(raw_path, "/pipeline")
    if raw_path.startswith("/visualize/") or path == "/visualize":
        return "visualizer", strip_prefix(raw_path, "/visualize")
    if path in COLLECTION_COMMANDS:
        return "collection", raw_path
    if (
        path == "/api"
        or raw_path.startswith("/api/")
        or path == "/replay"
        or raw_path.startswith("/replay/")
        or path == "/video"
        or raw_path.startswith("/video/")
        or path == "/lerobot-replay"
        or raw_path.startswith("/lerobot-replay/")
        or path == "/lerobot-video"
        or raw_path.startswith("/lerobot-video/")
    ):
        return "pipeline", raw_path
    return None, None


