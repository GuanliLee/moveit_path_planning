            f"collection to mark stage {stage_no}",
        )
        current_stage = as_int(status.get("current_stage"), stage_no + 1)
        log(f"stage {stage_no} marked by {topic}; current " + status_summary(status))
        set_status(
            "recording",
            recording_wait_message(episode),
            last_event=f"stage{stage_no}",
            active_stage=current_stage,
            completed_stages=as_int(status.get("completed_stages"), stage_no),
            episode_staged=True,
        )
        node.publish_ready(True, repeats=2)
        return status

    def save_current_episode(last_event: str = "end") -> dict:
        nonlocal phase, episode_staged, current_stage
        status = http.status()
        log("end received; current " + status_summary(status))
        if not status.get("capture_running"):
            log("save requested but collection was not running; " + status_summary(status))
            return status

        phase = "saving"
        sync_event_context()
        event_topic = grasp_end_topic if two_phase_enabled and capture_phase == "grasp" else end_topic
        node.publish_save_success(False)
        set_status(
            "saving",
            f"收到 {event_topic}=true，正在停止并保存本条数据；已发布 {ready_topic}=false。",
            last_event=last_event,
            active_stage=current_stage,
            episode_staged=episode_staged,
            **two_phase_status_fields(),
        )
        node.publish_ready(False, repeats=2)
        episode = status.get("episode")
        set_status(
            "saving",
            f"正在停止并保存 episode{episode}。",
            last_event=last_event,
            active_stage=current_stage,
            completed_stages=as_int(status.get("completed_stages"), 0),
            episode_staged=episode_staged,
            **two_phase_status_fields(),
        )
        http.post("/save")
        status = wait_for_status(
            http,
            lambda item: (not bool(item.get("capture_running"))) and save_review_finished(item, episode),
            save_timeout,
            "collection to finish saving and complete quality review",
        )
        log("collection saved; " + status_summary(status))
        episode_staged = False
        current_stage = 0
        return status

    def begin_two_phase_save(last_event: str) -> None:
        nonlocal phase, pending_review_episode, pending_review_phase
        nonlocal review_started_at, review_timeout_reported, review_completion_observed
        nonlocal resolved_review_transition, pending_place_start
        status = http.status()
        if not is_recording_status(status):
            raise RuntimeError(
                "two-phase save requested while collection is not recording; "
                + status_summary(status)
            )
        saved_episode = as_int(status.get("episode"), -1)
        if saved_episode != logical_episode:
            raise RuntimeError(
                f"collection episode {saved_episode} does not match logical episode {logical_episode}"
            )
        event_topic = grasp_end_topic if capture_phase == "grasp" else end_topic
        pending_review_episode = saved_episode
        pending_review_phase = capture_phase
        review_started_at = time.monotonic()
        review_timeout_reported = False
        review_completion_observed = False
        resolved_review_transition = None
        if capture_phase == "grasp":
            pending_place_start = False
        phase = "saving"
        sync_event_context()
        node.publish_save_success(False)
        set_status(
            "saving",
            f"收到 {event_topic}=true，正在停止并保存 episode{saved_episode}；"
            f"已发布 {ready_topic}=false。",
            last_event=last_event,
            active_stage=0,
            completed_stages=0,
            episode_staged=False,
            **two_phase_status_fields(),
        )
        node.publish_ready(False, repeats=2)
        http.post("/save")
        phase = "reviewing"
        sync_event_context()
        set_status(
            "reviewing",
            f"episode{saved_episode} {capture_phase}数据正在保存或等待质量评级；"
            "评级完成前的状态机事件都会被忽略。",
            last_event=last_event,
            active_stage=0,
            completed_stages=0,
            episode_staged=False,
            **two_phase_status_fields(),
        )

    def finish_two_phase_review_if_ready() -> bool:
        nonlocal phase, capture_phase, logical_episode
        nonlocal pending_review_episode, pending_review_phase, review_timeout_reported
        nonlocal review_completion_observed, resolved_review_transition
        nonlocal pending_place_start
        if pending_review_episode is None or not pending_review_phase:
            raise RuntimeError("reviewing state has no pending two-phase review")
        saved_status = http.status()
        transition = review_transition_or_cached(
            resolved_review_transition,
            saved_status,
            pending_review_phase,
            pending_review_episode,
            grasp_data_dir,
            place_data_dir,
        )
        if transition is None:
            review_completion_observed = False
            if (
                not review_timeout_reported
                and time.monotonic() - review_started_at >= save_timeout
            ):
                review_timeout_reported = True
                set_status(
                    "reviewing",
                    f"episode{pending_review_episode} {pending_review_phase}评级等待已超过"
                    f" {save_timeout:g} 秒；仍将继续等待，不会回拨或覆盖数据。",
                    last_event="review_timeout",
                    last_error="quality review wait exceeded warning threshold",
                    **two_phase_status_fields(),
                )
            return False

        resolved_review_transition = transition

        if not review_completion_observed:
            review_completion_observed = True
            set_status(
                "reviewing",
                f"episode{pending_review_episode} 评级已完成，正在丢弃评级期间积压的旧状态机事件。",
                last_event="review_complete_observed",
                **two_phase_status_fields(),
            )
            return False

        saved_episode = pending_review_episode
        saved_phase = pending_review_phase
        outcome, next_capture_phase, next_logical_episode, target_dir = transition
        configure_collection_for_target(
            http,
            data_dir=target_dir,
            episode_index=next_logical_episode,
        )
        discarded_events = discard_two_phase_transition_events(
            node,
            quiet_period=max(0.1, poll_interval * 2),
        )
        for discarded_event in discarded_events:
            event_name, received_capture_phase, received_runtime_phase = discarded_event
            if should_latch_place_start(
                event_name,
                pending_review_phase,
                received_capture_phase,
                received_runtime_phase,
            ):
                pending_place_start = True
                log(
                    f"latch place_start received during reviewed target switch; "
                    f"episode={pending_review_episode}"
                )
            else:
                log(
                    f"ignore two-phase event {event_name} received during reviewed target switch; "
                    f"capture_phase={pending_review_phase}, episode={pending_review_episode}"
                )
        release_place_start = should_release_latched_place_start(
            pending_place_start,
            saved_phase,
            outcome,
            next_capture_phase,
        )
        capture_phase = next_capture_phase
        logical_episode = next_logical_episode
        phase = "idle"
        pending_review_episode = None
        pending_review_phase = ""
        review_timeout_reported = False
        review_completion_observed = False
        resolved_review_transition = None
        pending_place_start = False
        sync_event_context()
        if outcome == "discarded":
            message = (
                f"episode{saved_episode} {saved_phase}数据已放弃；"
                f"{enabled_idle_message()}"
            )
        elif capture_phase == "place":
            if release_place_start:
                message = (
                    f"episode{saved_episode} 抓取数据已保存并完成评级；"
                    f"已消费评级期间锁存的 {place_start_topic}=true，将开启同编号放置录制。"
                )
            else:
                message = (
                    f"episode{saved_episode} 抓取数据已保存并完成评级；"
                    f"等待 {place_start_topic}=true 开启同编号放置录制。"
                )
        else:
            message = (
                f"episode{saved_episode} 放置数据已保存并完成评级；"
                f"等待 {start_topic}=true 开启 episode{logical_episode} 抓取录制。"
            )
        set_status(
            "idle",
            message,
            last_event="review_complete",
            active_stage=0,
            completed_stages=0,
            episode_staged=False,
            **two_phase_status_fields(),
        )
        node.publish_ready(False, repeats=2)
        observe_collection_status(saved_status)
        if release_place_start:
            node.events.put(("place_start", capture_phase, phase))
            log(
                f"requeue latched place_start in {capture_phase}/{phase}; "
                f"episode={logical_episode}"
            )
        return True

    try:
        log(
            "bridge ready: "
            f"start_topic={start_topic}, end_topic={end_topic}, ready_topic={ready_topic}, "
            f"save_success_topic={save_success_topic}, "
            f"stage_topics={stage_topics_for_status}, collection={collection_url}, "
            f"enabled={enabled}, staged_enabled={staged_enabled}, "
            f"two_phase_enabled={two_phase_enabled}, grasp_data_dir={grasp_data_dir}, "
            f"place_data_dir={place_data_dir}"
        )
        set_status(
            "idle" if enabled else "disabled",
            (
                enabled_idle_message()
                if enabled
                else "自动监听未启用；手动采集按钮可正常使用。"
            ),
            staged_enabled=staged_enabled,
            active_stage=0,
            completed_stages=0,
            episode_staged=False,
            **two_phase_status_fields(),
        )
        node.publish_ready(False, repeats=2)
        while rclpy.ok():
            if two_phase_enabled:
                time.sleep(0.05)
            else:
                try:
                    rclpy.spin_once(node, timeout_sec=0.1)
                except ExternalShutdownException:
                    break
            current_enabled = automation_enabled()
            current_staged_enabled = automation_staged_enabled()
            if current_enabled != enabled:
                enabled = current_enabled
                log(f"automatic collection {'enabled' if enabled else 'disabled'}")
                if not enabled:
                    if not two_phase_enabled:
                        phase = "idle"
                        sync_event_context()
                    save_success_armed = False
                    set_status(
                        "disabled",
                        "自动监听已关闭；手动采集按钮可正常使用。",
                        active_stage=0,
                        completed_stages=0,
                        episode_staged=False,
                        **two_phase_status_fields(),
                    )
                    node.publish_ready(False)
                    node.publish_save_success(False)
                else:
                    set_status(
                        "idle",
                        enabled_idle_message(),
                        active_stage=0,
                        completed_stages=0,
                        episode_staged=False,
                        **two_phase_status_fields(),
                    )
            if current_staged_enabled != staged_enabled:
                staged_enabled = current_staged_enabled
                log(f"staged automatic collection {'enabled' if staged_enabled else 'disabled'}")
                if phase == "idle":
                    set_status(
                        "idle" if enabled else "disabled",
                        enabled_idle_message() if enabled else "自动监听未启用；手动采集按钮可正常使用。",
                        staged_enabled=staged_enabled,
                        active_stage=0,
                        completed_stages=0,
                        episode_staged=False,
                        **two_phase_status_fields(),
                    )

            if two_phase_enabled and phase == "reviewing":
                try:
                    queued_review_event = node.events.get_nowait()
                except queue.Empty:
                    queued_review_event = None
                if queued_review_event is not None:
                    event_name, received_capture_phase, received_runtime_phase = queued_review_event
                    if should_latch_place_start(
                        event_name,
                        pending_review_phase,
                        received_capture_phase,
                        received_runtime_phase,
                    ):
                        pending_place_start = True
                        log(
                            f"latch place_start received while grasp review is pending; "
                            f"episode={pending_review_episode}"
                        )
                        set_status(
                            "reviewing",
                            f"episode{pending_review_episode} 抓取数据正在保存或等待评级；"
                            f"已锁存 {place_start_topic}=true，评级通过后将自动开启放置录制。",
                            last_event=event_name,
                            **two_phase_status_fields(),
                        )
                    else:
                        log(
                            f"ignore two-phase event {event_name} received while review is pending; "
                            f"capture_phase={capture_phase}, episode={pending_review_episode}"
                        )
                        set_status(
                            "reviewing",
                            f"episode{pending_review_episode} 正在保存或等待评级，"
                            f"已忽略事件 {event_name}；评级后需要新的状态机信号。",
                            last_event=event_name,
                            **two_phase_status_fields(),
                        )
                    continue
                try:
                    finish_two_phase_review_if_ready()
                except Exception as exc:  # noqa: BLE001 - retain recovery state and retry.
                    log(f"two-phase review reconciliation failed: {exc}")
                    set_status(
                        "reviewing",
                        f"评级结果已保留，切换下一采集目标失败，将继续重试：{exc}",
                        last_event="review_reconcile",
                        last_error=str(exc),
                        **two_phase_status_fields(),
                    )
                    node.publish_ready(False)
                continue

            now = time.monotonic()
            if enabled and now - last_status_poll_at >= max(0.05, poll_interval):
                last_status_poll_at = now
                try:
                    observe_collection_status(http.status())
                except Exception as exc:  # noqa: BLE001
                    log(f"collection status poll failed: {exc}")
                    node.publish_save_success(False)

            try:
                queued_event = node.events.get_nowait()
            except queue.Empty:
                continue

            if two_phase_enabled:
                event, received_capture_phase, received_runtime_phase = queued_event
                if not event_context_is_current(
                    received_capture_phase,
                    received_runtime_phase,
                    capture_phase,
                    phase,
                ):
                    log(
                        f"ignore stale two-phase event {event}; received in "
                        f"{received_capture_phase}/{received_runtime_phase}, current "
                        f"{capture_phase}/{phase}"
                    )
                    set_status(
                        phase,
                        f"已忽略旧状态事件 {event}：接收时为"
                        f"{received_capture_phase}/{received_runtime_phase}，"
                        f"当前为{capture_phase}/{phase}。",
                        last_event=event,
                        **two_phase_status_fields(),
                    )
                    continue
            else:
                event = queued_event

            if not enabled:
                log(f"ignore {event} while automatic collection is disabled")
                set_status("disabled", f"自动监听未启用，已忽略状态机事件 {event}。", last_event=event)
                node.publish_ready(False, repeats=1)
                save_success_armed = False
                node.publish_save_success(False)
                continue

            if two_phase_enabled:
                action = two_phase_event_action(capture_phase, phase, event)
                if action == "ignore":
                    log(
                        f"ignore two-phase event {event}; "
                        f"capture_phase={capture_phase}, runtime_phase={phase}"
                    )
                    set_status(
                        phase,
                        f"当前为{capture_phase}阶段/{phase}状态，已忽略乱序事件 {event}。",
                        last_event=event,
                        **two_phase_status_fields(),
                    )
                    continue

                try:
                    if action in {"start_grasp", "start_place"}:
                        target_dir = grasp_data_dir if capture_phase == "grasp" else place_data_dir
                        configure_collection_for_target(
                            http,
                            data_dir=target_dir,
                            episode_index=logical_episode,
                        )
                        topic = start_topic if action == "start_grasp" else place_start_topic
                        start_recording(
                            f"收到 {topic}=true，开启 episode{logical_episode} {capture_phase}录制",
                            event,
                            False,
                        )
                        continue

                    begin_two_phase_save(event)
                except Exception as exc:  # noqa: BLE001 - keep bridge alive for operator recovery.
                    log(f"ERROR handling two-phase action {action}: {exc}")
                    if action in {"save_grasp", "save_place"} and pending_review_episode is not None:
                        phase = "reviewing"
                    else:
                        phase = "idle"
                    sync_event_context()
                    set_status(
                        "reviewing" if phase == "reviewing" else "error",
                        f"抓取+放置双阶段流程失败：{exc}",
                        last_event=event,
                        last_error=str(exc),
                        **two_phase_status_fields(),
                    )
                    node.publish_ready(False)
                continue

            if event == "start":
                if phase in {"starting", "saving"}:
                    log(f"ignore start while phase={phase}")
                    continue
                if phase == "recording":
                    status = http.status()
                    if is_recording_status(status):
                        log("start received while already recording; confirmed by status, republish ready=true")
                        set_status(
                            "recording",
                            recording_wait_message(status.get("episode")),
                            last_event="start",
                            active_stage=current_stage,
                            completed_stages=as_int(status.get("completed_stages"), 0),
                            episode_staged=episode_staged,
                        )
                        node.publish_ready(True)
                        continue
                    log("local recording phase was stale; collection status is " + status_summary(status))
                    phase = "idle"

                try:
                    start_recording(
                        f"收到 {start_topic}=true，开启本条采集",
                        "start",
                        automation_staged_enabled(),
                    )
                except Exception as exc:  # noqa: BLE001 - keep bridge alive after one failed cycle.
                    log(f"ERROR starting collection: {exc}")
                    set_status(
                        "error",
                        f"本条录制启动失败：{exc}",
                        last_event="start",
                        last_error=str(exc),
                        active_stage=current_stage,
                        episode_staged=episode_staged,
                    )
                    node.publish_ready(False)
                    save_success_armed = False
                    node.publish_save_success(False)
                    phase = "idle"
                continue

            if event.startswith("stage:"):
                _, stage_text, topic = event.split(":", 2)
                stage_no = int(stage_text)
                if not episode_staged:
                    log(f"ignore staged event {event} while current episode is not staged")
                    set_status(
                        phase if phase != "idle" else "idle",
                        f"当前未按分阶段模式采集，已忽略 {topic}=true。",
                        last_event=f"stage{stage_no}",
                        active_stage=current_stage,
                        episode_staged=episode_staged,
                    )
                    continue
                if phase != "recording":
                    log(f"ignore staged event {event} while phase={phase}")
                    set_status(
                        phase,
                        f"当前状态为 {phase}，已忽略阶段事件 {topic}=true。",
                        last_event=f"stage{stage_no}",
                        active_stage=current_stage,
                        episode_staged=episode_staged,
                    )
                    continue
                if stage_no != current_stage:
                    log(f"ignore staged event {event}; expected stage {current_stage}")
                    set_status(
                        "recording",
                        f"收到阶段 {stage_no} 事件 {topic}=true，但当前等待阶段 {current_stage}，已忽略。",
                        last_event=f"stage{stage_no}",
                        active_stage=current_stage,
                        episode_staged=True,
                    )
                    continue
                if current_stage > 4:
                    log(f"ignore staged event {event}; waiting final end")
                    set_status(
                        "recording",
                        f"已进入阶段 5，等待 {end_topic}=true 保存，已忽略 {topic}=true。",
                        last_event=f"stage{stage_no}",
                        active_stage=current_stage,
                        episode_staged=True,
                    )
                    continue
                try:
                    mark_stage_boundary(stage_no, topic)
                except Exception as exc:  # noqa: BLE001
                    log(f"ERROR marking stage {stage_no}: {exc}")
                    set_status(
                        "error",
                        f"阶段 {stage_no} 切换失败：{exc}",
                        last_event=f"stage{stage_no}",
                        last_error=str(exc),
                        active_stage=current_stage,
                        episode_staged=True,
                    )
                    node.publish_ready(False)
                    node.publish_save_success(False)
                    phase = "recording"
                continue

            if event == "end":
                if phase in {"idle", "starting"}:
                    try:
                        status = http.status()
                    except Exception as exc:  # noqa: BLE001
                        log(f"end received while phase={phase}; status unavailable: {exc}")
                        set_status("error", f"收到结束信号但读取采集状态失败：{exc}", last_event="end", last_error=str(exc))
                        node.publish_ready(False)
                        phase = "idle"
                        continue
                    if not status.get("capture_running"):
                        log("end received but collection is not recording; " + status_summary(status))
                        set_status(
                            "idle",
                            f"收到 {end_topic}=true，但当前没有正在录制；等待 {start_topic}=true 开启本条采集。",
                            last_event="end",
                            active_stage=0,
                            completed_stages=0,
                            episode_staged=False,
                        )
                        node.publish_ready(False)
                        phase = "idle"
                        continue
                    phase = "recording"

                if phase == "saving":
                    log("ignore end while saving")
                    set_status("saving", "正在保存当前 episode，已忽略重复结束信号。", last_event="end")
                    continue

                try:
                    if episode_staged and current_stage < 5:
                        log(f"final end received before stage 5; current_stage={current_stage}")
                    saved_status = save_current_episode("end")
                    observe_collection_status(saved_status)
                    saved_message = saved_status.get("message")
                    next_episode = saved_status.get("episode")
                    set_status(
                        "idle",
                        f"保存完成，已切到 episode{next_episode}；等待 {start_topic}=true 开启下一条采集。",
                        last_event="end",
                        active_stage=0,
                        completed_stages=0,
                        episode_staged=False,
                    )
                    if saved_message:
                        log(f"save result message: {saved_message}")
                    node.publish_ready(False)
                    phase = "idle"
                except Exception as exc:  # noqa: BLE001
                    log(f"ERROR saving collection: {exc}")
                    set_status(
                        "error",
                        f"自动停止/保存失败：{exc}",
                        last_event="end",
                        last_error=str(exc),
                        active_stage=current_stage,
                        episode_staged=episode_staged,
                    )
                    node.publish_ready(False)
                    save_success_armed = False
                    node.publish_save_success(False)
                    phase = "idle"
                continue
    finally:
        try:
            node.publish_ready(False, repeats=2)
            node.publish_save_success(False, repeats=2)
        except Exception:
            pass
        if ros_executor is not None:
            ros_executor.shutdown(timeout_sec=1.0)
        if ros_spin_thread is not None:
            ros_spin_thread.join(timeout=1.0)
        node.destroy_node()
        if rclpy.ok():
            rclpy.shutdown()
    return 0


